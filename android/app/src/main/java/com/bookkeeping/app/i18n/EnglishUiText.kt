    fun translate(chinese: String): String {
        english[chinese]?.let { return it }
        // These historical sync status messages contain dynamic IDs/counts.
        // Translate them only at the presentation layer, never in the journal.
        if (chinese.startsWith("本地交易 ") && chinese.endsWith(" 数据异常，无法同步")) {
            val id = chinese.removePrefix("本地交易 ").removeSuffix(" 数据异常，无法同步")
            return "Local transaction $id is invalid and cannot sync"
        }
        if (chinese.startsWith("服务器返回 ") && chinese.endsWith("，稍后重试")) {
            val code = chinese.removePrefix("服务器返回 ").removeSuffix("，稍后重试")
            return "Server returned $code; retrying later"
        }
        if (chinese.startsWith("旧交易 ") && chinese.endsWith(" 金额待核对；未擅自修改")) {
            val id = chinese.removePrefix("旧交易 ").removeSuffix(" 金额待核对；未擅自修改")
            return "Old transaction $id needs an amount review; no automatic correction was made"
        }
        if (chinese.startsWith("已上传；其中 ") &&
            chinese.endsWith(" 条未被旧版服务端接收，记录仍保留在手机")) {
            val count = chinese.removePrefix("已上传；其中 ")
                .removeSuffix(" 条未被旧版服务端接收，记录仍保留在手机")
            return "Uploaded; $count records were not accepted by the older server and remain on your phone"
        }
        if (chinese.startsWith("已同步无冲突交易；仍有 ") &&
            chinese.endsWith(" 笔修改待核对，请不要卸载应用")) {
            val count = chinese.removePrefix("已同步无冲突交易；仍有 ")
                .removeSuffix(" 笔修改待核对，请不要卸载应用")
            return "Synced non-conflicting records; $count changes still need review. Do not uninstall."
        }
        if (chinese.startsWith("已同步；还有 ") && chinese.endsWith(" 笔修改待上传")) {
            val count = chinese.removePrefix("已同步；还有 ").removeSuffix(" 笔修改待上传")
            return "Synced; $count changes still to upload"
        }
        if (chinese.startsWith("有 ") && chinese.endsWith(" 笔冲突待处理；其余修改已上传")) {
            val count = chinese.removePrefix("有 ").removeSuffix(" 笔冲突待处理；其余修改已上传")
            return "$count conflicts need review; other changes were uploaded"
        }
        if (chinese.startsWith("正在释放语音模型 ")) {
            return "Unpacking voice model " + chinese.removePrefix("正在释放语音模型 ")
        }
        if (chinese.startsWith("无法读取 XLSX：")) {
            return "Could not read XLSX: " + chinese.removePrefix("无法读取 XLSX：")
        }
        if (chinese.startsWith("无法解析交易时间：")) {
            return "Could not parse transaction time: " + chinese.removePrefix("无法解析交易时间：")
        }
        if (chinese.startsWith("无法解析金额：")) {
            return "Could not parse amount: " + chinese.removePrefix("无法解析金额：")
        }
        if (chinese.startsWith("状态需人工确认：")) {
            return "Status needs review: " + chinese.removePrefix("状态需人工确认：")
        }
        if (chinese.startsWith("文件内重复，首次出现在第 ") && chinese.endsWith(" 行")) {
            val row = chinese.removePrefix("文件内重复，首次出现在第 ").removeSuffix(" 行")
            return "Duplicate in this file; first occurrence on row $row"
        }
        if (chinese.startsWith("导入失败，未写入任何记录：")) {
            return "Import failed; nothing was written: " +
                chinese.removePrefix("导入失败，未写入任何记录：")
        }
        if (chinese.startsWith("超过最大行数 ") && chinese.endsWith("，已停止解析")) {
            val rows = chinese.removePrefix("超过最大行数 ").removeSuffix("，已停止解析")
            return "Exceeded the maximum number of rows ($rows); parsing stopped"
        }
        return chinese
    }

