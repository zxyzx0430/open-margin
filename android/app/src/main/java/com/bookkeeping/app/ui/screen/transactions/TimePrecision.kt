package com.bookkeeping.app.ui.screen.transactions

/**
 * 这次记账的时间有多精确。决定「同商户 + 同金额」允许多大的时间差才算疑似重复。
 *
 * 为什么不在规则里固定 1 天：同一家店每天买同价咖啡是常态，1 天窗口会天天弹；
 * 但缩到 1 小时又会漏掉「昨天中午」这种只说了哪天、没说钟点的补录。
 * 所以让调用方把「用户到底说了什么」传进来，规则按精度分档。
 */
enum class TimePrecision(
    /** 同商户分支的时间窗口（前后各多少毫秒）。 */
    val sameMerchantWindowMs: Long,
) {
    /** 说了具体钟点（「昨晚八点」），或手填时改了时分：±1 小时。 */
    PRECISE(60L * 60L * 1000L),

    /**
     * 只说了哪一天（「昨天中午」没钟点）：±12 小时。
     *
     * 表单里的时间保留「现在」的时分，±12 小时足以覆盖这一整天，
     * 又不会跨到前两天。
     */
    DATE_ONLY(12L * 60L * 60L * 1000L),

    /** 连日期都没说，按「现在」记账：保守按精确处理，避免把隔天同价误判成重复。 */
    NONE(60L * 60L * 1000L),
}
